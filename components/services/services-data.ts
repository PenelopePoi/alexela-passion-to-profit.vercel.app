export const ADD_ONS = SERVICES.filter(s => s.addOn);
export const MAIN_SERVICES = SERVICES.filter(s => !s.addOn);

export function getServicesByCategory(category: ServiceCategory): Service[] {
  return MAIN_SERVICES.filter(s => s.category === category);
}

export function getServicesByTier(tier: 'budget' | 'premium' | 'elite'): Service[] {
  return MAIN_SERVICES.filter(s => s.tier === tier);
}

export function getAddOnsForService(service: Service): Service[] {
  return ADD_ONS.filter(a =>
    a.addOnFor?.includes('all') || a.addOnFor?.includes(service.category)
  );
}

export function calculateBundleDiscount(count: number): number {
  if (count >= 5) return 0.15;
  if (count >= 3) return 0.10;
  return 0;
}

export function calculateBundleTotal(services: Service[]): {
  subtotal: number;
  discount: number;
  discountPercent: number;
  total: number;
} {
  const subtotal = services.reduce((sum, s) => sum + s.price, 0);
  const discountPercent = calculateBundleDiscount(services.length);
  const discount = subtotal * discountPercent;
  return { subtotal, discount, discountPercent, total: subtotal - discount };
}
